mod assertions;
mod marked_text;

pub use assertions::*;
pub use marked_text::*;

/// 生成指定行数、列数并以指定字符开头的示例文本。
pub fn sample_text(rows: usize, cols: usize, start_char: char) -> String {
    let mut text = String::new();
    for row in 0..rows {
        let c: char = (start_char as u32 + row as u32) as u8 as char;
        let mut line = c.to_string().repeat(cols);
        if row < rows - 1 {
            line.push('\n');
        }
        text += &line;
    }
    text
}
